test("macOS probes preserve the command alias and invalidate legacy target-based version evidence", () => {
  const endpoint: CliExecutableEndpoint = {
    id: "rustc-alias",
    commandName: "rustc",
    kind: "symlink",
    path: "/Users/fixture/.cargo/bin/rustc",
    canonicalPath: "/Users/fixture/.cargo/bin/rustup",
    symlinkTarget: "/Users/fixture/.cargo/bin/rustup",
    accessible: true,
    executable: true,
    targetExists: true,
    fingerprint: "legacy",
  };
  assert.equal(resolveProbeExecutable(endpoint, "darwin"), endpoint.path);
  assert.equal(
    resolveProbeExecutable({ ...endpoint, executable: false }, "darwin"),
    undefined,
  );
  // Fingerprint generated by v1.10.0 before launcher-preserving probes.
  assert.notEqual(
    createEndpointFingerprint(endpoint, "darwin"),
    "fp-3a188616ac0eff996e0a84e0",
  );
});

test(
  "real POSIX proxy aliases report independent compiler, package-manager and proxy versions",
  { skip: process.platform === "win32" },
  async () => {
    const root = await realpath(
      await mkdtemp(path.join(os.tmpdir(), "clis-posix-proxy-")),
    );
    try {
      const proxy = path.join(root, "rustup");
      await writeFile(
        proxy,
        `#!/bin/sh
case "\${0##*/}" in
  rustc) printf 'rustc 1.93.0\\n';;
  cargo) printf 'cargo 1.93.0\\n';;
  *) printf 'rustup 1.28.2\\n';;
esac
`,
      );
      await chmod(proxy, 0o755);
      await symlink(proxy, path.join(root, "rustc"));
      await symlink(proxy, path.join(root, "cargo"));
      const environment: CliScanEnvironment = {
        platform: "darwin",
        architecture: "arm64",
        env: {},
        homeDirectory: root,
        pathValue: root,
        pathExtValue: "",
        knownDirectories: [],
        neutralWorkingDirectory: root,
        testMode: true,
      };
      const cancellation = new CliCancellationToken();
      const records = await enumerateCliPathEndpoints({
        platform: "darwin",
        snapshot: { directories: [root], pathExt: [], pathDirectoryCount: 1 },
        cancellation,
      });
      const inventory = assembleInventory({
        environment,
        mutable: matchInstallations(environment, records, []),
        previous: null,
        failedSourceIds: new Set(),
        now: Date.now(),
      });
      await probeVersions({
        environment,
        runner: new RealCliCommandRunner(root),
        cancellation,
        ...inventory,
        previous: null,
        onProgress: () => undefined,
      });
      for (const productId of ["rustc", "cargo"]) {
        assert.equal(
          inventory.installations.find((i) => i.productId === productId)
            ?.version,
          "1.93.0",
        );
      }
      assert.equal(
        inventory.installations.find((i) => i.productId === "rustup")?.version,
        "1.28.2",
      );
    } finally {
      await rm(root, { recursive: true, force: true });
    }
  },
);
